projectRoot = fileparts(fileparts(fileparts(mfilename("fullpath"))));
sessionRoot = fileparts(mfilename("fullpath"));
addpath(fullfile(projectRoot, "Tools"));

rawRoot = fullfile(sessionRoot, "raw", "prbs");
modelRoot = fullfile(sessionRoot, "models");
plotRoot = fullfile(sessionRoot, "plots");

cases = [ ...
    struct("name", "amp1200_sw40ms", ...
           "train", "yaw_prbs_amp1200_sw40ms_train_run01.csv", ...
           "valid", "yaw_prbs_amp1200_sw40ms_valid_run01.csv"); ...
    struct("name", "amp1200_sw20ms", ...
           "train", "yaw_prbs_amp1200_sw20ms_train_run01.csv", ...
           "valid", "yaw_prbs_amp1200_sw20ms_valid_run01.csv") ...
];

for k = 1:numel(cases)
    close all force;
    result = analyze_sysid(fullfile(rawRoot, cases(k).train), ...
                           fullfile(rawRoot, cases(k).valid));
    save(fullfile(modelRoot, "yaw_" + cases(k).name + "_models.mat"), "result");

    validationFigure = findobj("Type", "figure", ...
                               "Name", "Plant model validation");
    residualFigure = findobj("Type", "figure", ...
                             "Name", "Identification residuals");
    exportgraphics(validationFigure, ...
        fullfile(plotRoot, "yaw_" + cases(k).name + "_validation.png"), ...
        "Resolution", 160);
    exportgraphics(residualFigure, ...
        fullfile(plotRoot, "yaw_" + cases(k).name + "_residuals.png"), ...
        "Resolution", 160);
end

close all force;
